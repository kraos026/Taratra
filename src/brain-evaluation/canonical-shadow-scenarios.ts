function scenario(input: {
  caseId: string;
  title: string;
  companyContext: string;
  process: string;
  roles: readonly string[];
  tools: readonly string[];
  workflow: readonly string[];
  volumes: Readonly<Record<string, number | string>>;
  durations: Readonly<Record<string, number | string>>;
  manualWork: readonly string[];
  painPoints: readonly string[];
  risks: readonly string[];
  constraints: readonly string[];
  evidence: readonly {
    readonly id: string;
    readonly source: string;
    readonly statement: string;
    readonly reliability: number;
    readonly supports: readonly string[];
  }[];
  expectedFindings: readonly string[];
  expectedRootCauses: readonly string[];
  expectedBottlenecks: readonly string[];
  expectedOpportunities: readonly string[];
  forbiddenInventions: readonly string[];
  expectedExclusions: readonly string[];
  expectedPriorityOrder: readonly string[];
  expectedRoiDirection: BenchmarkCase["hiddenGroundTruth"]["expectedRoiDirection"];
  expectedOutcome?: BenchmarkCase["scoringMetadata"]["expectedOutcome"];
  adversarial?: boolean;
  uncertaintyRequired?: boolean;
  roiIndeterminate?: boolean;
  humanReviewRequired?: boolean;
  multiOpportunity?: boolean;
  expectedDeferrals?: readonly string[];
  expectedRejections?: readonly string[];
  expectedProcessRemediation?: readonly string[];
  expectedEvidenceRequests?: readonly string[];
  expectedRisks?: readonly string[];
  expectedHumanReview?: readonly string[];
  criticalFailureConditions?: readonly string[];
  requiredEvidence: readonly string[];
  risksToRecognize: readonly string[];
  aliases: Readonly<Record<string, readonly string[]>>;
}): BenchmarkCase {
  return deepFreeze({
    publicInput: {
      caseId: input.caseId,
      title: input.title,
      companyContext: input.companyContext,
      process: input.process,
      roles: input.roles,
      tools: input.tools,
      workflow: input.workflow,
      volumes: input.volumes,
      durations: input.durations,
      manualWork: input.manualWork,
      painPoints: input.painPoints,
      risks: input.risks,
      constraints: input.constraints,
      evidence: input.evidence.map(({ id, source, statement, reliability }) => ({
        id,
        source,
        statement,
        reliability,
      })),
    },
    scoringMetadata: {
      aliases: input.aliases,
      evidenceMappings: input.evidence.map(({ id, supports }) => ({
        evidenceId: id,
        supports,
      })),
      expectedOutcome: input.expectedOutcome ?? "AUTOMATE_NOW",
      adversarial: input.adversarial ?? false,
      uncertaintyRequired: input.uncertaintyRequired ?? false,
      roiIndeterminate:
        input.roiIndeterminate ??
        (input.expectedRoiDirection === "INSUFFICIENT_EVIDENCE" ||
          input.expectedRoiDirection === "STRATEGIC_NON_QUANTIFIED"),
      humanReviewRequired: input.humanReviewRequired ?? false,
      multiOpportunity:
        input.multiOpportunity ??
        input.expectedOpportunities.length + (input.expectedProcessRemediation?.length ?? 0) > 1,
    },
    hiddenGroundTruth: {
      expectedFindings: concepts(input.expectedFindings),
      expectedRootCauses: concepts(input.expectedRootCauses),
      expectedBottlenecks: concepts(input.expectedBottlenecks),
      expectedOpportunities: concepts(input.expectedOpportunities),
      forbiddenInventions: concepts(input.forbiddenInventions, true),
      expectedExclusions: concepts(input.expectedExclusions),
      expectedPriorityOrder: input.expectedPriorityOrder,
      expectedRoiDirection: input.expectedRoiDirection,
      expectedDeferrals: input.expectedDeferrals ?? [],
      expectedRejections: input.expectedRejections ?? [],
      expectedProcessRemediation: input.expectedProcessRemediation ?? [],
      expectedEvidenceRequests: input.expectedEvidenceRequests ?? [],
      expectedRisks: input.expectedRisks ?? input.risksToRecognize,
      expectedHumanReview: input.expectedHumanReview ?? [],
      requiredEvidence: input.requiredEvidence,
      risksToRecognize: input.risksToRecognize,
      criticalFailureConditions: input.criticalFailureConditions ?? input.forbiddenInventions,
    },
  });
}

