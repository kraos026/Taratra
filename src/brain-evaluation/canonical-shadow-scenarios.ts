interface DesignedCase {
  readonly caseId: string;
  readonly title: string;
  readonly companyContext: string;
  readonly process: string;
  readonly roles: readonly string[];
  readonly tools: readonly string[];
  readonly workflow: readonly string[];
  readonly volumes: Readonly<Record<string, number | string>>;
  readonly durations: Readonly<Record<string, number | string>>;
  readonly manualWork: readonly string[];
  readonly painPoints: readonly string[];
  readonly risks: readonly string[];
  readonly constraints: readonly string[];
  readonly evidence: readonly ReturnType<typeof evidence>[];
  readonly truth: {
    readonly outcome: BenchmarkCase["scoringMetadata"]["expectedOutcome"];
    readonly adversarial?: boolean;
    readonly uncertainty?: boolean;
    readonly roiIndeterminate?: boolean;
    readonly human?: boolean;
    readonly multi?: boolean;
    readonly expectedFindings: readonly string[];
    readonly expectedRootCauses: readonly string[];
    readonly expectedBottlenecks: readonly string[];
    readonly expectedOpportunities: readonly string[];
    readonly deferrals?: readonly string[];
    readonly rejections?: readonly string[];
    readonly remediation?: readonly string[];
    readonly priority: readonly string[];
    readonly roi: BenchmarkCase["hiddenGroundTruth"]["expectedRoiDirection"];
    readonly evidenceRequests?: readonly string[];
    readonly risks: readonly string[];
    readonly humanReview?: readonly string[];
    readonly exclusions: readonly string[];
    readonly forbidden: readonly string[];
    readonly criticalFailures?: readonly string[];
  };
}

function designedCase(
  caseId: string,
  title: string,
  companyContext: string,
  process: string,
  roles: readonly string[],
  tools: readonly string[],
  workflow: readonly string[],
  volumes: Readonly<Record<string, number | string>>,
  durations: Readonly<Record<string, number | string>>,
  manualWork: readonly string[],
  painPoints: readonly string[],
  risks: readonly string[],
  constraints: readonly string[],
  evidenceItems: readonly ReturnType<typeof evidence>[],
  truth: DesignedCase["truth"],
): DesignedCase {
  return {
    caseId,
    title,
    companyContext,
    process,
    roles,
    tools,
    workflow,
    volumes,
    durations,
    manualWork,
    painPoints,
    risks,
    constraints,
    evidence: evidenceItems,
    truth,
  };
}

function evidence(
  id: string,
  source: string,
  statement: string,
  reliability: number,
  supports: readonly string[],
) {
  return { id, source, statement, reliability, supports };
}

function concepts(ids: readonly string[], critical = false) {
  return ids.map((id) => ({
    id,
    label: label(id),
    aliases: [label(id), id.replaceAll("_", " ")],
    critical,
  }));
}

function label(id: string): string {
  return id.replaceAll("_", " ");
}

function deepFreeze<T>(value: T): T {
  if (value && typeof value === "object") {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}
