export function databasePoolConfig(connectionString: string): {
  connectionString: string;
  ssl?: { ca: string; rejectUnauthorized: true };
} {
  let url: URL;
  try {
    url = new URL(connectionString);
  } catch {
    throw new Error("DATABASE_URL must be a valid PostgreSQL URL");
  }
  if (url.protocol !== "postgres:" && url.protocol !== "postgresql:") {
    throw new Error("DATABASE_URL must be a valid PostgreSQL URL");
  }

  const supabaseHost =
    /^db\.[a-z0-9-]+\.supabase\.co$/.test(url.hostname) ||
    /^[a-z0-9.-]+\.pooler\.supabase\.com$/.test(url.hostname);
  if (!supabaseHost) return { connectionString };

  // pg parses URL parameters after PoolConfig; they must not replace strict TLS
  // or redirect a verified Supabase hostname to a different endpoint.
  if (url.searchParams.has("host")) {
    throw new Error("Supabase DATABASE_URL must not override its hostname");
  }
  for (const key of ["ssl", "sslmode", "sslcert", "sslkey", "sslrootcert", "uselibpqcompat"]) {
    url.searchParams.delete(key);
  }
  return {
    connectionString: url.href,
    ssl: { ca: SUPABASE_ROOT_CA, rejectUnauthorized: true },
  };
}
